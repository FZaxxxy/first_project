/** PWM 频率（Hz）。舵机常用 50Hz（周期 20ms） */
#define PCA9685_PWM_FREQ_HZ         50u

/** 关节 -> 舵机通道 映射表。
 *
 *  6 个关节舵机分布在两块级联板上，每块板通道 0~15。
 *  此处定义"关节 n 接到 哪块板 的 哪个通道"。
 *  ★ 须自定义：按你的实际接线修改。下面为示例：
 *      关节 1~3  -> 板 1 (addr 0x40) 通道 0/1/2
 *      关节 4~6  -> 板 2 (addr 0x41) 通道 0/1/2
 *      夹爪       -> 板 2 通道 3
 */
#define SERVO_JOINT_BOARD(_j)   ((_j) <= 3 ? 1 : 2)   /* 关节 -> 板号 */
#define SERVO_JOINT_CH(_j)      ((_j) - 1) % 3        /* 关节 -> 板内通道 */

/** 夹爪舵机位置（板号、通道） */
#define GRIPPER_BOARD           2
#define GRIPPER_CHANNEL         3

/** 夹爪 开/合 对应脉宽（ms）
 *  ★ 须自定义：按夹爪舵机实际开合角度标定 */
#define GRIPPER_OPEN_MS         1.2f
#define GRIPPER_CLOSE_MS        1.8f

/* ==================================================================
 * 二、舵机参数（角度 -> 脉宽 线性映射）
 * ================================================================== */

/** 舵机最小脉宽（0 度对应，ms）典型 0.5ms */
